public class RelationalOperators {
    public static void main(String[] args) {

        int x = 5;
        int y = 6;

        boolean result = x < y;
        System.out.println("x<y: " + result);

        result = x > y;
        System.out.println("x>y: " + result);

        result = x <= y;
        System.out.println("x<=y: " + result);

        result = x >= y;
        System.out.println("x>=y: " + result);

        result = x == y;
        System.out.println("x==y: " + result);

        result = x != y;
        System.out.println("x!=y: " + result);

    }
}
